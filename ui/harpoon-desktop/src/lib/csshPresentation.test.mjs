import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

const viewSource = readFileSync(new URL("../views/CsshWorkspace.tsx", import.meta.url), "utf8");
const mainSource = readFileSync(new URL("../main.tsx", import.meta.url), "utf8");
const containersSource = readFileSync(new URL("../views/ContainersView.tsx", import.meta.url), "utf8");
const styleSource = readFileSync(new URL("../styles/primitives.css", import.meta.url), "utf8");

test("CSSH keeps recipient selection separate from independent tile shells", () => {
  assert.match(containersSource, /<CsshWorkspace project=\{group\.project\} containers=\{group\.containers\} \/>/);
  assert.match(viewSource, /containerLifecycleState\(container\) === "running"/);
  assert.match(viewSource, /<ShellTab context="harpoon" containerId=\{id\} running connectRequest=\{connectAllRequest\}/);
  assert.match(viewSource, /hasFullContainerId/);
  assert.match(viewSource, /disabled=\{!isEligible\}/);
  assert.match(viewSource, /const selectAll = \(\) =>/);
  assert.match(viewSource, /const connectAll = \(\) =>/);
  assert.match(viewSource, /connectRequest=\{connectAllRequest\}/);
  assert.match(viewSource, /Connect all/);
  assert.match(viewSource, /run_universal_command/);
  assert.doesNotMatch(viewSource, /recordDiagnostic|startDiagnosticHeartbeat|traceId/);
  assert.match(viewSource, /Run on \{selectedContainers\.length\}/);
  assert.match(viewSource, /transcripts\[id\]/);
  assert.match(viewSource, /never write into interactive PTY sessions/);
  assert.match(viewSource, /dispatchTargets = selectedContainers\.map/);
  assert.match(viewSource, /setCommand\(""\)/);
  assert.match(viewSource, /setCommand\(dispatchCommand\)/);
  assert.match(viewSource, /commandPendingRef\.current/);
  assert.match(viewSource, /finally \{ commandPendingRef\.current = false;/);
  assert.match(viewSource, /setCommandPending\(false\)/);
  assert.match(viewSource, /setCommand\(dispatchCommand\); setCommandMessage\(`Command could not run/);
  assert.match(viewSource, /Command result/);
  assert.match(viewSource, /MAX_TRANSCRIPT_COMMANDS = 20/);
  assert.match(viewSource, /MAX_TRANSCRIPT_OUTPUT_BYTES = 256 \* 1024/);
  assert.match(viewSource, /history\.length > MAX_TRANSCRIPT_COMMANDS/);
  assert.match(viewSource, /outputBytes > MAX_TRANSCRIPT_OUTPUT_BYTES/);
  assert.match(viewSource, /role="log"/);
  assert.match(viewSource, /independent runs/);
  assert.match(viewSource, /mountedRef/);
  assert.match(viewSource, /mountedRef\.current = true/);
  assert.match(mainSource, /<React\.StrictMode>/);
  assert.match(viewSource, /aria-pressed/);
  assert.match(viewSource, /cssh-tile__view--hidden/);
  assert.doesNotMatch(viewSource, /onClick=\{\(\) => toggle/);
  assert.match(styleSource, /\.cssh-tile\.is-selected \{ border-color: var\(--accent-yellow\)/);
  assert.match(styleSource, /\.cssh-tile__view > \.shell-tab/);
  assert.match(styleSource, /\.cssh-tile__mode/);
  assert.match(styleSource, /\.cssh-tile__header-actions/);
  assert.match(styleSource, /\.cssh-result__entry/);
  assert.match(styleSource, /prefers-reduced-motion/);
  assert.match(styleSource, /grid-auto-rows: minmax\(0, 292px\)/);
  assert.match(styleSource, /\.cssh-tile \{ display: flex; min-width: 0; min-height: 0; height: 292px/);
});
